import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { JSDOM } from 'jsdom';

test('exact label autofill handles nested select text and stale question/approval blocks submission', () => {
  const dom = new JSDOM('<main><form><label>Full name<input required></label><label>Location<select><option>Cairo</option><option>Remote</option></select></label><button type="button">Submit Application</button></form></main>', { url: 'https://www.linkedin.com/jobs/view/test', runScripts: 'outside-only' });
  const w = dom.window;
  w.HTMLElement.prototype.getClientRects = () => [{ width: 100, height: 20 }];
  Object.defineProperty(w.HTMLElement.prototype, 'innerText', { get() { return this.textContent; } });
  let handler; let clicked = 0;
  w.chrome = { runtime: { id: 'test', onMessage: { addListener: fn => { handler = fn; } } } };
  w.document.querySelector('form button').onclick = () => { clicked++; };
  for (const file of ['policy.js', 'content.js']) w.eval(fs.readFileSync(new URL('../../extension/' + file, import.meta.url), 'utf8'));
  const send = message => { let result; handler(message, { id: 'test' }, value => { result = value; }); return result; };
  const payload = { version: 1, match_score: 8, dry_run: true, safety: { readiness_verified: true, caps_and_duplicates_checked: true, resume_verified: true }, answers: [{ label: 'Full name', value: 'Alex River', verified: true }, { label: 'Location', value: 'Remote', verified: true }] };
  const fill = () => send({ type: 'fill', text: JSON.stringify(payload) });
  assert.equal(fill().filled, 2);
  assert.equal(w.document.querySelector('select').value, 'Remote');
  assert.match(send({ type: 'submit', attested: true }).error, /dry_run/);
  payload.dry_run = false;
  assert.equal(fill().filled, 2);
  assert.match(send({ type: 'submit', attested: false }).error, /Confirm/);
  fill();
  const newQuestion = w.document.createElement('input');
  w.document.querySelector('form').append(newQuestion);
  assert.match(send({ type: 'submit', attested: true }).error, /questions or answers changed/);
  newQuestion.remove();
  assert.equal(fill().filled, 2);
  assert.match(send({ type: 'submit', attested: true }).note, /Clicked once/);
  assert.equal(clicked, 1);
  assert.match(send({ type: 'submit', attested: true }).error, /review again/);
  assert.equal(clicked, 1);
  dom.window.close();
});